def get_ultra_bot_routes(api_router):
    """Register Ultra Conversion Bot routes"""
    
    @api_router.get("/ultra-bot/generate/{count}")
    async def generate_articles(count: int = 50):
        """Generate conversion-optimized articles"""
        if count > 100:
            count = 100
        articles = ultra_bot.generate_daily_articles(count)
        return {
            "success": True,
            "generated": len(articles),
            "articles": articles
        }
    
    @api_router.get("/ultra-bot/stats")
    async def get_stats():
        """Get bot statistics"""
        return ultra_bot.get_stats()
    
    @api_router.get("/ultra-bot/keywords")
    async def get_keywords():
        """Get all SEO keywords"""
        return ultra_bot.get_all_keywords()
    
    @api_router.get("/ultra-bot/articles")
    async def get_articles():
        """Get generated articles"""
        return {
            "count": len(ultra_bot.articles),
            "articles": ultra_bot.articles
        }
    
    @api_router.post("/ultra-bot/index")
    async def index_articles():
        """Index articles for search engines"""
        return ultra_bot.index_articles()
    
    @api_router.get("/ultra-bot/article/{article_id}")
    async def get_article(article_id: str):
        """Get specific article"""
        for article in ultra_bot.articles:
            if article["id"] == article_id or article["slug"] == article_id:
                return article
        return {"error": "Article not found"}
    
    return api_router
